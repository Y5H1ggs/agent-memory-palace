"""evaluation_domains.py - 广覆盖的领域标注集（100 个领域）。

为什么要这么多领域：6 个领域能调参数，但调出来的阈值仍然可能是「这 6 个领域
恰好都长这样」的产物。领域一多，**不适用的边界会自己浮出来** —— 0.20 的弃答线
在六领域上就已经误弃 4 条，正是这样被发现的。

这里每个领域只标**检索与弃答**（6 条记忆 / 4 条查询），不标去重对与沉淀簇：
那两个组件需要「同一件事的两种写法」与「同一主题的三个碎片」，
手工标 100 套的成本远大于收益，也没法在 6 条记忆上稳定成立。
所以：**广覆盖看检索与弃答，深标注看去重与沉淀**（`evaluation.py` 里那 6 个领域）。
这句话必须写在 README 里，否则「100 个领域」会变成一句没有边界的话。

数据格式（刻意压平，方便肉眼审）：

    ("key", "中文名", [(名字, 内容, "标签|标签"), ...], [(查询, "gold|gold", "kind"), ...])

`kind` 取 exact / paraphrase / unanswerable；unanswerable 的 gold 为空串。
"""
