# 不可答的那条**故意**问的是别的领域的东西：它同时测「会不会硬凑」。
SPECS: list[tuple[str, str, list[tuple[str, str, str]], list[tuple[str, str, str]]]] = []


def _add(key, label, memories, queries) -> None:
    SPECS.append((key, label, memories, queries))


