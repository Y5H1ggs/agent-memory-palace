def build_datasets() -> dict[str, Dataset]:
    """把 SPECS 变成 Dataset。领域名加 `zh-` 前缀，与既有六领域保持同一命名。

    每个领域额外塞一条**跨领域**的不可答查询：从别的领域借一条真实提问，标成
    unanswerable。这比手写「今天天气怎么样」强得多 —— 它测的是「会不会拿本领域的
    记忆去硬凑另一个领域的问题」，而不是「会不会回答完全不相关的话」。
    """
    out: dict[str, Dataset] = {}
    for key, _label, memories, queries in SPECS:
        name = f"zh-{key}"
        out[name] = Dataset(
            name=name,
            memories=[(n, c, tuple(t.split("|"))) for n, c, t in memories],
            queries=[
                Query(q, tuple(g.split("|")) if g else (), kind)
                for q, g, kind in queries
            ],
        )

    names = list(out)
    for index, name in enumerate(names):
        # 固定偏移保证可复现，又不至于总是借相邻领域（相邻的往往话题接近）
        donor = out[names[(index + 37) % len(names)]]
        borrowed = next(q for q in donor.queries if q.kind != "unanswerable")
        out[name].queries.append(Query(borrowed.text, (), "unanswerable"))
    return out


